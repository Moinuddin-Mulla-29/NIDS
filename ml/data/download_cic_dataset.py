def load_and_standardize_csv(filepath: str, max_rows: int = 50000) -> pd.DataFrame:
    """
    Standardize column names across different CICFlowMeter output versions.
    Removes leading/trailing whitespace, handles case differences.
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Dataset file not found at: {filepath}")

    print(f"[*] Loading dataset from {filepath} (max_rows={max_rows})...")
    df = pd.read_csv(filepath, nrows=max_rows, low_memory=False)
    # Strip column whitespaces which are common in CIC-IDS2017 CSVs
    df.columns = df.columns.str.strip()
    return df

